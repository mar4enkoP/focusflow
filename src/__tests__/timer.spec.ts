import { beforeEach, afterEach, describe, it, expect, vi } from 'vitest'
import { setActivePinia } from 'pinia'
import { createOwnedPinia as createPinia } from './workspaceTestUtils'
import { useTasksStore } from '../stores/tasks'
import { useTimerStore } from '../stores/timer'
describe('focus timer', () => {
  beforeEach(() => {
    vi.useFakeTimers()
    vi.setSystemTime(100000)
    setActivePinia(createPinia())
  })
  afterEach(() => vi.useRealTimers())
  function setup() {
    const tasks = useTasksStore()
    tasks.save({ title: 'First', duration: 1, category: 'Work' })
    tasks.save({ title: 'Second', duration: 2, category: 'Study' })
    const timer = useTimerStore()
    timer.select(tasks.tasks[0]!.id)
    return { tasks, timer }
  }
  it('updates the selected timer after editing its duration, including before first start', () => {
    const { tasks, timer } = setup()
    const task = tasks.tasks[0]!
    tasks.save({ ...task, duration: 25 }, task.id)
    expect(timer.remaining).toBe(25 * 60000)
    tasks.save({ ...task, duration: 6 }, task.id)
    expect(timer.remaining).toBe(6 * 60000)
    timer.start()
    vi.advanceTimersByTime(10000)
    timer.sync()
    expect(timer.remaining).toBe(350000)
  })
  it('preserves elapsed time when editing a cached or running timer', () => {
    const { tasks, timer } = setup()
    const task = tasks.tasks[0]!
    timer.start()
    vi.advanceTimersByTime(20000)
    timer.select(tasks.tasks[1]!.id)
    tasks.save({ ...task, duration: 6 }, task.id)
    timer.select(task.id)
    expect(timer.remaining).toBe(340000)
    timer.start()
    vi.advanceTimersByTime(10000)
    tasks.save({ ...task, duration: 2 }, task.id)
    expect(timer.remaining).toBe(90000)
    vi.advanceTimersByTime(10000)
    timer.sync()
    expect(timer.remaining).toBe(80000)
  })
  it('uses elapsed timestamps despite missing ticks; pause/resume and repeated start are safe', () => {
    const { timer } = setup()
    timer.start()
    vi.setSystemTime(120000)
    timer.start()
    timer.pause()
    expect(timer.remaining).toBe(40000)
    vi.setSystemTime(200000)
    timer.sync()
    expect(timer.remaining).toBe(40000)
    timer.start()
    vi.setSystemTime(230000)
    timer.sync()
    expect(timer.remaining).toBe(10000)
  })
  it('expires without completing and can extend or reset', () => {
    const { tasks, timer } = setup()
    timer.start()
    vi.setSystemTime(180000)
    timer.sync()
    expect(timer.state).toBe('expired')
    expect(tasks.remaining).toBe(2)
    timer.start()
    expect(timer.state).toBe('expired')
    timer.addTime()
    expect(timer.remaining).toBe(300000)
    timer.start()
    vi.setSystemTime(190000)
    timer.addTime()
    expect(timer.remaining).toBe(590000)
    timer.reset()
    expect(timer.remaining).toBe(60000)
    expect(timer.state).toBe('ready')
  })
  it('preserves paused sessions across switches and advances on manual completion', () => {
    const { tasks, timer } = setup()
    const first = tasks.tasks[0]!.id
    const second = tasks.tasks[1]!.id
    timer.start()
    vi.setSystemTime(110000)
    timer.select(second)
    expect(timer.state).toBe('ready')
    timer.select(first)
    expect(timer.remaining).toBe(50000)
    timer.complete()
    expect(tasks.tasks[0]!.completed).toBe(true)
    expect(timer.selectedId).toBe(second)
    expect(timer.state).toBe('ready')
    timer.complete()
    expect(timer.task).toBeUndefined()
    timer.start()
    expect(timer.state).toBe('ready')
  })
  it('handles removal, completion from list, and duration edits without corrupting a session', () => {
    const { tasks, timer } = setup()
    timer.start()
    tasks.save({ title: 'Edited', duration: 3, category: 'Work' }, timer.selectedId)
    expect(timer.remaining).toBe(180000)
    timer.reset()
    expect(timer.remaining).toBe(180000)
    tasks.remove(timer.selectedId!)
    expect(timer.task?.title).toBe('Second')
    tasks.toggle(timer.selectedId!)
    expect(timer.task).toBeUndefined()
  })
})
