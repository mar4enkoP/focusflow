import { nextTick } from 'vue'
import { afterEach, describe, it, expect, vi } from 'vitest'
import { createPinia } from 'pinia'
import { mount } from '@vue/test-utils'
import App from '../App.vue'
import { useTimerStore } from '../stores/timer'
import { useTasksStore } from '../stores/tasks'
const wrappers: ReturnType<typeof mount>[] = []
function setup() {
  const pinia = createPinia()
  const wrapper = mount(App, { global: { plugins: [pinia] }, attachTo: document.body })
  wrappers.push(wrapper)
  return { wrapper, store: useTasksStore(pinia), timer: useTimerStore(pinia) }
}
afterEach(() => {
  vi.restoreAllMocks()
  wrappers.forEach((w) => w.unmount())
  wrappers.length = 0
})
describe('task manager', () => {
  it('navigates categories by keyboard and dismisses the menu before the form', async () => {
    const { wrapper } = setup()
    const focus = vi.spyOn(HTMLElement.prototype, 'focus')
    await wrapper.get('#task-category').trigger('keydown', { key: 'ArrowDown' })
    await nextTick()
    expect(document.activeElement?.getAttribute('role')).toBe('option')
    expect(focus).toHaveBeenLastCalledWith({ preventScroll: true })
    expect((wrapper.get('#category-options').element as HTMLElement).style.position).toBe('fixed')
    await wrapper.get('[role="listbox"]').trigger('keydown', { key: 'End' })
    expect(document.activeElement?.textContent).toContain('Reading')
    await wrapper.get('[role="listbox"]').trigger('keydown', { key: 'Escape' })
    expect(wrapper.find('[role="listbox"]').exists()).toBe(false)
    expect(document.activeElement?.id).toBe('task-category')
    expect(wrapper.find('form').exists()).toBe(true)
    await wrapper.get('button.quiet').trigger('click')
    expect(wrapper.find('form').exists()).toBe(false)
    expect(document.activeElement?.id).toBe('list-title')
  })
  it('opens focus without starting, hides empty content, and preserves editing', async () => {
    const { wrapper, store, timer } = setup()
    await wrapper.get('#task-title').setValue('First task')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.find('.empty').exists()).toBe(false)
    expect(wrapper.findAll('[aria-label="Add a task"]')).toHaveLength(1)
    expect(wrapper.get('[aria-label="Add a task"]').text()).toBe('Add task')
    expect(wrapper.text()).not.toContain('Create a task')
    await wrapper.get('.start-focus').trigger('click')
    expect(timer.selectedId).toBe(store.tasks[0]!.id)
    expect(timer.state).toBe('ready')
    expect(wrapper.get('.dock-time').text()).toContain('0% \u00b7')
    expect(wrapper.get('[role="timer"]').text()).toBe('25:00')
    expect(wrapper.text()).toContain('Planned \u00b7 25 min')
    await wrapper.get('[aria-label="Start or resume timer"]').trigger('click')
    expect(timer.state).toBe('running')
    await wrapper.get('[aria-label="Pause timer"]').trigger('click')
    expect(timer.state).toBe('paused')
    await wrapper.get('[aria-label="Open task panel"]').trigger('click')
    expect(wrapper.find('.empty').exists()).toBe(false)
    await wrapper.get('[aria-label="Edit First task"]').trigger('click')
    await wrapper.get('#task-title').setValue('Edited task')
    await wrapper.get('form').trigger('submit')
    expect(store.tasks[0]!.title).toBe('Edited task')
    await wrapper.get('.start-focus').trigger('click')
    expect(timer.state).toBe('paused')
    expect(wrapper.text()).toContain('Edited task')
  })
  it('skips completed tasks and retains an explicit selection', async () => {
    const { wrapper, store, timer } = setup()
    store.save({ title: 'Done', duration: 5, category: 'Work' })
    store.save({ title: 'Next', duration: 10, category: 'Work' })
    store.save({ title: 'Chosen', duration: 15, category: 'Work' })
    store.toggle(store.tasks[0]!.id)
    await wrapper.get('form').trigger('keydown', { key: 'Escape' })
    await wrapper.get('.start-focus').trigger('click')
    expect(timer.task?.title).toBe('Next')
    await wrapper.get('[aria-label="Open task panel"]').trigger('click')
    await wrapper.get('[aria-label="Focus on Chosen"]').trigger('click')
    await wrapper.get('[aria-label="Open task panel"]').trigger('click')
    await wrapper.get('.start-focus').trigger('click')
    expect(timer.task?.title).toBe('Chosen')
    expect(timer.state).toBe('ready')
    expect(wrapper.get('.dock-time').text()).toContain('0% \u00b7')
    store.tasks.forEach((task) => {
      if (!task.completed) store.toggle(task.id)
    })
    await nextTick()
    await wrapper.get('[aria-label="Back to tasks"]').trigger('click')
    expect(wrapper.find('.empty').exists()).toBe(false)
    expect(wrapper.find('.start-focus').exists()).toBe(false)
  })
  it('validates fields inline and keeps entered values', async () => {
    const { wrapper, store } = setup()
    expect(wrapper.text()).toContain('Add your first task')
    await wrapper.get('#task-title').setValue('   ')
    await wrapper.get('#task-duration').setValue('0')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.text()).toContain('Give your task a title.')
    expect(wrapper.text()).toContain('Choose a whole number')
    expect(store.tasks).toHaveLength(0)
    expect(document.activeElement?.id).toBe('task-title')
    await wrapper.get('#task-title').setValue('Read a chapter')
    await wrapper.get('form').trigger('submit')
    expect((wrapper.get('#task-title').element as HTMLInputElement).value).toBe('Read a chapter')
    expect(document.activeElement?.id).toBe('task-duration')
  })
  it('adds, reorders, completes, reopens, edits, cancels and deletes through working controls', async () => {
    const { wrapper, store } = setup()
    await wrapper.get('#task-title').setValue('First')
    await wrapper.get('#task-duration').setValue('40')
    await wrapper.get('#task-category').trigger('click')
    await wrapper
      .findAll('[role="option"]')
      .find((option) => option.text().includes('Reading'))!
      .trigger('click')
    await wrapper.get('form').trigger('submit')
    const id = store.tasks[0]!.id
    expect(wrapper.get('[aria-label="Task list"]').text()).toContain('40 min')
    await wrapper.get('[aria-label="Add a task"]').trigger('click')
    await wrapper.get('#task-title').setValue('Second')
    await wrapper.get('form').trigger('submit')
    await wrapper
      .get('[aria-label="Reorder Second; use arrow keys"]')
      .trigger('keydown', { key: 'ArrowUp' })
    expect(store.tasks[0]!.title).toBe('Second')
    await wrapper.get('[aria-label="Complete First"]').setValue(true)
    expect(wrapper.text()).toContain('40 min \u00b7 Completed')
    expect(store.remaining).toBe(1)
    await wrapper.get('[aria-label="Complete First"]').setValue(false)
    expect(store.remaining).toBe(2)
    await wrapper.get('[aria-label="Edit First"]').trigger('click')
    expect((wrapper.get('#task-title').element as HTMLInputElement).value).toBe('First')
    await wrapper.get('#task-title').setValue('Updated')
    await wrapper.get('#task-duration').setValue('15')
    await wrapper.get('#task-category').trigger('click')
    await wrapper
      .findAll('[role="option"]')
      .find((option) => option.text().includes('Health'))!
      .trigger('click')
    await wrapper.get('form').trigger('submit')
    expect(store.tasks.find((t) => t.id === id)).toMatchObject({
      title: 'Updated',
      duration: 15,
      category: 'Health',
    })
    await wrapper.get('[aria-label="Edit Updated"]').trigger('click')
    await wrapper.get('#task-title').setValue('Discard')
    await wrapper.get('form').trigger('keydown', { key: 'Escape' })
    expect(wrapper.text()).toContain('Updated')
    expect(wrapper.text()).not.toContain('Discard')
    await wrapper.get('[aria-label="Delete Updated"]').trigger('click')
    expect(store.tasks.map((t) => t.title)).toEqual(['Second'])
    await wrapper.get('[aria-label="Delete Second"]').trigger('click')
    expect(wrapper.text()).toContain('No tasks yet')
    expect(wrapper.text()).toContain('0 tasks to do')
  })
})
